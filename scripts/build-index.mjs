#!/usr/bin/env node
// Builds recipes/index.json (the catalog the site and `launchfilm ref search` read) from
// studio/src/recipes/*/recipe.json. Deterministic (sorted, no timestamps) so CI can --check it.
// Usage: node scripts/build-index.mjs [--check]
import {existsSync, mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {readJson, recipeDirs, ROOT, stable} from './lib.mjs';

const check = process.argv.includes('--check');
const recipes = recipeDirs().map((dir) => {
	const r = readJson(path.join(dir, 'recipe.json'));
	return {
		id: r.id,
		title: r.title,
		summary: r.summary,
		family: r.family,
		tags: r.tags ?? [],
		techniques: r.techniques ?? [],
		use_when: r.use_when ?? [],
		format: r.format,
		theme: r.look?.theme ?? null,
		music: r.audio?.music ? {bpm: r.audio.music.bpm ?? null, energy: r.audio.music.energy ?? null} : null,
		vo: Boolean(r.audio?.vo),
		difficulty: r.difficulty,
		render_cost: r.render_cost ?? null,
		inputs: r.inputs ?? {},
		source: r.source ? {name: r.source.name, url: r.source.url, author: r.source.author ?? null} : null,
		preview: r.preview ?? null,
		path: `studio/src/recipes/${path.basename(dir)}`,
	};
});
recipes.sort((a, b) => a.id.localeCompare(b.id));
const families = [...new Set(recipes.map((r) => r.family))].sort();
const out = stable({$comment: 'Generated by scripts/build-index.mjs from studio/src/recipes/*/recipe.json. Do not edit.', version: 1, count: recipes.length, families, recipes});
const file = path.join(ROOT, 'recipes', 'index.json');
if (check) {
	const cur = existsSync(file) ? readFileSync(file, 'utf8') : '';
	if (cur !== out) {
		console.error('recipes/index.json is stale: run node scripts/build-index.mjs and commit it');
		process.exit(1);
	}
	console.log(`recipes/index.json up to date (${recipes.length} recipes)`);
} else {
	mkdirSync(path.dirname(file), {recursive: true});
	writeFileSync(file, out);
	console.log(`recipes/index.json: ${recipes.length} recipes, families: ${families.join(', ') || '-'}`);
}
