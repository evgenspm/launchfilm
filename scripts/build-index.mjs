#!/usr/bin/env node
// Builds the recipe catalog from studio/src/recipes/*/recipe.json:
//   recipes/index.json  machine catalog (`launchfilm ref search` and agents read it)
//   recipes/CATALOG.md  the same recipes grouped by family, one line each, for people and agents
// Deterministic (sorted, no timestamps) so CI can --check both files.
// Usage: node scripts/build-index.mjs [--check]
import {existsSync, mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {readJson, recipeDirs, ROOT, stable} from './lib.mjs';

const check = process.argv.includes('--check');

// family order and one-line notes follow schemas/recipe.schema.json (enum order) and reference-study measure.md §10
const FAMILIES = [
	['launch-film', 'whole launch stories, hook to payoff'],
	['product-ui', 'the product UI, rebuilt or recorded, staged by the camera'],
	['ai-chat', 'prompt, thinking and answer'],
	['mobile-app', 'phone-first products'],
	['kinetic-type', 'the text is the picture'],
	['logo-brand', 'mark and logo moments, end cards'],
	['transitions', 'the cut is the subject'],
	['social-promo', 'vertical social formats'],
	['3d-device', 'devices and objects in 3D space'],
	['data-stats', 'charts, counters and numbers'],
];

const hasCode = (dir) => existsSync(path.join(dir, 'Recipe.tsx')) && existsSync(path.join(dir, 'index.tsx'));

const loaded = recipeDirs().map((dir) => ({dir, r: readJson(path.join(dir, 'recipe.json')), code: hasCode(dir)}));
loaded.sort((a, b) => a.r.id.localeCompare(b.r.id));

// ---------------------------------------------------------------- recipes/index.json
const recipes = loaded.map(({dir, r, code}) => ({
	id: r.id,
	title: r.title,
	summary: r.summary,
	family: r.family,
	tags: r.tags ?? [],
	techniques: r.techniques ?? [],
	use_when: r.use_when ?? [],
	format: r.format,
	theme: r.look?.theme ?? null,
	music: r.audio?.music ? {bpm: r.audio.music.bpm ?? null, energy: r.audio.music.energy ?? null} : null,
	vo: Boolean(r.audio?.vo),
	difficulty: r.difficulty,
	render_cost: r.render_cost ?? null,
	inputs: r.inputs ?? {},
	source: r.source ? {name: r.source.name, url: r.source.url, author: r.source.author ?? null} : null,
	status: r.status ?? 'studied',
	code,
	...(r.preview ? {preview: r.preview} : {}),
	path: `studio/src/recipes/${path.basename(dir)}`,
}));
const families = [...new Set(recipes.map((r) => r.family))].sort();
const indexOut = stable({$comment: 'Generated by scripts/build-index.mjs from studio/src/recipes/*/recipe.json. Do not edit.', version: 1, count: recipes.length, families, recipes});

// ---------------------------------------------------------------- recipes/CATALOG.md
const md = (s) => String(s ?? '').replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
const num = (n) => String(Number(Number(n).toFixed(2)));

const formatPart = (r) => {
	const f = r.format ?? {};
	const music = r.audio?.music;
	const sound = [r.audio?.vo ? 'VO' : 'no VO', music?.present ? (music.bpm ? `music ${Math.round(music.bpm)} BPM` : 'music') : 'no music'];
	return [f.aspect === 'other' ? 'other aspect' : f.aspect, `${num(f.duration_s)} s`, r.look?.theme, sound.join(', ')].filter(Boolean).join(' · ');
};

const techniquesPart = (r) => {
	const t = r.techniques ?? [];
	return t.slice(0, 4).join(', ') + (t.length > 4 ? ` +${t.length - 4}` : '');
};

const plural = (n, one, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;
const inputsPart = (r) => {
	const i = r.inputs ?? {};
	const need = [];
	if (i.product_name) need.push('product name');
	if (i.logo) need.push('logo');
	if (i.tagline) need.push('tagline');
	if (i.lines) need.push(plural(i.lines, 'line'));
	if (i.stats) need.push(plural(i.stats, 'stat'));
	if (i.screenshots) need.push(plural(i.screenshots, 'screenshot'));
	if (i.screen_recording) need.push('screen recording');
	if (i.ui_rebuild) need.push('UI rebuilt in React');
	if (i.url) need.push('URL');
	return need.length ? `needs: ${need.join(', ')}` : 'needs: nothing beyond your brand';
};

const sourcePart = (r) => {
	const s = r.source ?? {};
	let label = s.name && s.name !== 'other' ? s.name : s.author;
	if (!label) {
		try {
			label = new URL(s.url).hostname.replace(/^www\./, '');
		} catch {
			label = 'source';
		}
	}
	return s.url ? `source: [${md(label).replace(/[[\]]/g, '')}](${s.url})` : 'source: none';
};

const statusPart = (r, code) => (code ? 'code' : 'text') + ((r.status ?? 'studied') === 'reviewed' ? ' (reviewed)' : '');

const line = ({dir, r, code}) => {
	const id = path.basename(dir);
	return `- [\`${id}\`](../studio/src/recipes/${id}/recipe.md) | ${md(r.title)} | ${formatPart(r)} | ${techniquesPart(r)} | ${inputsPart(r)} | ${sourcePart(r)} | ${statusPart(r, code)}`;
};

const known = new Map(FAMILIES);
const order = [...FAMILIES.map(([f]) => f), ...families.filter((f) => !known.has(f))];
const groups = order.map((f) => [f, loaded.filter((x) => x.r.family === f)]).filter(([, list]) => list.length);
const withCode = loaded.filter((x) => x.code).length;

const catalogOut =
	[
		'# Recipe catalog',
		'',
		'Generated by `scripts/build-index.mjs` from `studio/src/recipes/*/recipe.json`; do not edit by hand. The same data',
		'for scripts: [index.json](index.json).',
		'',
		'A recipe is one published launch film, studied frame by frame and written down so an agent can rebuild its craft for',
		'another product: a beat sheet with times and frame counts, the camera and motion of every shot (named springs,',
		'staggers, transitions), the sound on each event, the look, and the inputs you need to supply. It links to the',
		'original and never copies its footage or its words. Every recipe is text (`recipe.md` + `recipe.json`), and that is',
		'enough to build a film from. Recipes marked `code` also have a ready `Recipe.tsx` to start from.',
		'',
		'To use one, watch its source link, then ask your agent:',
		'',
		'```text',
		'make a 30s launch film for my product from recipe <id>',
		'```',
		'',
		'The agent (the `recipes` skill) reads the beat sheet, re-times it to your length and music, and builds the scenes in',
		'your brand from the studio presets and components. You can combine up to 3 recipes (the hook from one, the features',
		'from another, the end card from a third), or describe the style you want and let the agent pick.',
		'',
		'Each line: `id` (links to its recipe.md) | title | aspect · length · theme · voice, music | main techniques | what you need | source | text or code',
		'',
		`${plural(loaded.length, 'recipe')}: ${!withCode ? 'all text' : withCode === loaded.length ? 'all with code' : `${loaded.length - withCode} text only, ${withCode} also with code`}.` +
			(groups.length ? ` Families: ${groups.map(([f, list]) => `[${f}](#${f}) (${list.length})`).join(' · ')}.` : ''),
		'',
		...groups.flatMap(([f, list]) => [`## ${f}`, '', ...(known.has(f) ? [`${known.get(f)[0].toUpperCase()}${known.get(f).slice(1)}.`, ''] : []), ...list.map(line), '']),
	]
		.join('\n')
		.replace(/\n+$/, '\n');

// ---------------------------------------------------------------- write or check
const outputs = [
	[path.join(ROOT, 'recipes', 'index.json'), indexOut],
	[path.join(ROOT, 'recipes', 'CATALOG.md'), catalogOut],
];
if (check) {
	const stale = outputs.filter(([file, out]) => (existsSync(file) ? readFileSync(file, 'utf8') : '') !== out).map(([file]) => path.relative(ROOT, file));
	if (stale.length) {
		console.error(`${stale.join(' and ')} ${stale.length > 1 ? 'are' : 'is'} stale: run node scripts/build-index.mjs and commit the result`);
		process.exit(1);
	}
	console.log(`recipes/index.json and recipes/CATALOG.md up to date (${recipes.length} recipes)`);
} else {
	for (const [file, out] of outputs) {
		mkdirSync(path.dirname(file), {recursive: true});
		writeFileSync(file, out);
	}
	console.log(`recipes/index.json + recipes/CATALOG.md: ${recipes.length} recipes (${recipes.length - withCode} text, ${withCode} with code), families: ${families.join(', ') || '-'}`);
}
